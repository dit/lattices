def lattice_from_covers(nodes, covers):
    """
    Build a lattice from its Hasse cover edges.

    Parameters
    ----------
    nodes : collection
        The lattice elements.
    covers : collection of (greater, lesser)
        Cover relations with the greater element first.

    Returns
    -------
    lattice : Lattice
    """
    import networkx as nx

    nodes = list(nodes)
    graph = nx.DiGraph()
    graph.add_nodes_from(nodes)
    for greater, lesser in covers:
        graph.add_edge(greater, lesser)

    def relationship(a, b):
        if a == b:
            return True
        return nx.has_path(graph, b, a)

    return Lattice(nodes, relationship)


def fm3_lattice():
    """
    Return Dedekind's free modular lattice on three generators.
    """
    nodes = [FM3_NODES[index] for index in range(len(FM3_NODES))]
    covers = [(nodes[greater], nodes[lesser]) for greater, lesser in FM3_COVERS]
    return lattice_from_covers(nodes, covers)
